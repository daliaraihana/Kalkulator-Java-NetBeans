    private void btnSamaDenganActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSamaDenganActionPerformed
        // TODO add your handling code here:
        angka2 = Double.parseDouble(txtLayar.getText());
        switch (operasi) {
            case "tambah" -> hasil = angka1 + angka2;
            case "kurang" -> hasil = angka1 - angka2;
            case "kali"   -> hasil = angka1 * angka2;
            case "bagi"   -> hasil = (angka2 != 0) ? angka1 / angka2 : 0; 
        }

        // Menghilangkan format .0 jika hasilnya bilangan bulat
        if (hasil % 1 == 0) {
            txtLayar.setText(String.valueOf((int) hasil));
        } else {
            txtLayar.setText(String.valueOf(hasil));
        }
        statusInputBaru = true;
    }//GEN-LAST:event_btnSamaDenganActionPerformed

